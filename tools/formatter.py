"""
Pure markdown rendering for briefings. No LLM, no I/O: same inputs, same output.
"""

from __future__ import annotations

from datetime import datetime

from models.schemas import Signal

IMPACT_ORDER = {"high": 0, "medium": 1, "low": 2}
IMPACT_LABEL = {"high": "HIGH", "medium": "MEDIUM", "low": "LOW"}


def order_signals(signals: list[Signal], competitors: list[str]) -> list[Signal]:
    """Canonical order: competitor (as configured), then impact high->low, then confidence.
    Signal numbers [n] used in prompts and the briefing refer to this order."""
    rank = {c: i for i, c in enumerate(competitors)}
    return sorted(
        signals,
        key=lambda s: (rank.get(s.competitor, len(rank)), IMPACT_ORDER[s.impact_assessment], -s.confidence),
    )


def signals_to_context_block(signals: list[Signal]) -> str:
    """Numbered compact listing for LLM prompts. Assumes `signals` is already ordered."""
    if not signals:
        return "No signals."
    return "\n".join(
        f"[{i}] {s.competitor} | {s.signal_type} | impact={s.impact_assessment} | {s.title}: {s.summary}"
        for i, s in enumerate(signals, 1)
    )


def format_briefing(
    *,
    run_id: str,
    run_date: datetime,
    competitors: list[str],
    signals: list[Signal],
    executive_summary: str | None,
    strategic_implications: list[str],
    signals_to_watch: list[str],
    retry_counts: dict[str, int] | None = None,
) -> str:
    """Render the briefing. `signals` must already be in `order_signals` order.
    A None executive_summary means the narrative step failed; we say so instead
    of inventing filler."""
    retry_counts = retry_counts or {}
    numbered = list(enumerate(signals, 1))
    date_str = run_date.strftime("%Y-%m-%d")

    lines = [
        f"# CompeteIQ Briefing: {date_str}",
        "",
        f"- **Run ID:** `{run_id}`",
        f"- **Competitors:** {', '.join(competitors)}",
        f"- **Signals:** {len(signals)}",
        "",
        "## Executive Summary",
        "",
    ]
    if not signals:
        lines.append("_No signals met the grounding and confidence thresholds this run._")
    elif executive_summary is None:
        lines.append("_Narrative unavailable for this run (synthesis step failed). Signals below are complete._")
    else:
        lines.append(executive_summary.strip())

    lines += ["", "## Key Developments", ""]
    for comp in competitors:
        comp_signals = [(n, s) for n, s in numbered if s.competitor == comp]
        lines += [f"### {comp}", ""]
        if not comp_signals:
            retries = retry_counts.get(comp, 0)
            note = f" after {retries} re-search{'es' if retries != 1 else ''}" if retries else ""
            lines += [f"_No grounded signals found{note}._", ""]
            continue
        for n, s in comp_signals:
            label = s.signal_type.replace("_", " ").title()
            lines.append(
                f"- **[{n}] {label}: {s.title}** ({IMPACT_LABEL[s.impact_assessment]} impact, "
                f"confidence {s.confidence:.2f})  \n  {s.summary} [source]({s.source_url})"
            )
        lines.append("")

    if signals and executive_summary is not None:
        lines += ["## Strategic Implications", ""]
        lines += [f"- {_clean_bullet(p)}" for p in strategic_implications] or ["_None identified._"]
        lines += ["", "## Signals to Watch", ""]
        lines += [f"- {_clean_bullet(w)}" for w in signals_to_watch] or ["_None identified._"]
        lines.append("")

    lines += ["---", f"_Generated by CompeteIQ on {date_str}. Every development links to the page it was extracted from._", ""]
    return "\n".join(lines)


def _clean_bullet(text: str) -> str:
    return text.strip().lstrip("-•* ").strip()
